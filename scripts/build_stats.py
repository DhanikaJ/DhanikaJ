#!/usr/bin/env python3
"""Builds assets/stats.svg from the GitHub API (run by the workflow; no third-party widget servers).
Env: GITHUB_TOKEN (optional but avoids rate limits), GH_USER (default DhanikaJ).
Offline test: python3 build_stats.py --mock"""
import json, os, sys, urllib.request
from collections import Counter
from datetime import datetime, timezone
from html import escape
from pathlib import Path

USER = os.environ.get("GH_USER", "DhanikaJ")
OUT = Path(__file__).resolve().parent.parent / "assets" / "stats.svg"
COLORS = ["#58e6aa", "#79c0ff", "#d2a8ff", "#ffa657", "#ff7b72", "#8b949e"]

def api(path):
    req = urllib.request.Request("https://api.github.com" + path, headers={
        "Accept": "application/vnd.github+json", "User-Agent": "profile-stats"})
    if os.environ.get("GITHUB_TOKEN"):
        req.add_header("Authorization", "Bearer " + os.environ["GITHUB_TOKEN"])
    with urllib.request.urlopen(req, timeout=20) as r:
        return json.load(r)

def collect():
    if "--mock" in sys.argv:
        return 13, 9, 1, Counter({"Java": 52000, "TypeScript": 41000, "HTML": 16000, "Kotlin": 9000, "CSS": 4000})
    user = api(f"/users/{USER}")
    repos = [r for r in api(f"/users/{USER}/repos?per_page=100&type=owner") if not r["fork"]]
    langs = Counter()
    for r in repos:
        try:
            langs.update(api(f"/repos/{USER}/{r['name']}/languages"))
        except Exception:
            pass
    stars = sum(r["stargazers_count"] for r in repos)
    return user["public_repos"], len(repos), user["followers"], langs, stars

def main():
    data = collect()
    repos, own, followers, langs = data[0], data[1], data[2], data[3]
    top = langs.most_common(5)
    total = sum(v for _, v in top) or 1
    W, H = 900, 190
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-label="GitHub stats and top languages">',
         '<style>text{font-family:Consolas,Menlo,"DejaVu Sans Mono",monospace}.k{fill:#8b949e;font-size:12px}.v{fill:#c9d1d9;font-size:26px;font-weight:700}'
         '.l{fill:#c9d1d9;font-size:12px}.bar{transform-box:fill-box;transform-origin:left;animation:grow 1.2s cubic-bezier(.2,.8,.2,1) both}'
         '@keyframes grow{from{transform:scaleX(0)}}@media (prefers-reduced-motion:reduce){.bar{animation:none}}</style>',
         f'<rect width="{W}" height="{H}" rx="14" fill="#0d1117" stroke="#30363d"/>']
    for i, (label, val) in enumerate([("public repos", repos), ("original repos", own), ("followers", followers)]):
        x = 36 + i * 150
        o.append(f'<text x="{x}" y="70" class="v">{val}</text><text x="{x}" y="92" class="k">{escape(label)}</text>')
    o.append('<text x="36" y="38" class="k">// github stats, generated by my own workflow</text>')
    o.append('<text x="500" y="38" class="k">// top languages</text>')
    x0, bw, y = 500, 364, 52
    cx = x0
    for i, (name, v) in enumerate(top):
        w = bw * v / total
        o.append(f'<rect class="bar" x="{cx:.1f}" y="{y}" width="{max(w-2,2):.1f}" height="10" rx="3" fill="{COLORS[i]}" style="animation-delay:{i*0.12:.2f}s"/>')
        cx += w
    for i, (name, v) in enumerate(top):
        col, row = i % 2, i // 2
        lx, ly = x0 + col * 190, 98 + row * 24
        o.append(f'<circle cx="{lx+5}" cy="{ly-4}" r="5" fill="{COLORS[i]}"/><text x="{lx+18}" y="{ly}" class="l">{escape(name)}  {v/total*100:.0f}%</text>')
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    o.append(f'<text x="36" y="{H-18}" class="k">updated {stamp}</text></svg>')
    OUT.write_text("\n".join(o))
    print("wrote", OUT)

main()
